#!/usr/bin/env bash
# Start the three demo ION nodes (ROVER ipn:99, LUNAR GATEWAY ipn:50,
# EARTH ipn:23) on this host.
#
#   ion/start_nodes.sh [CONTACT_PLAN]
#
# CONTACT_PLAN is an ionrc(5) file of contacts and ranges with relative times
# (default: ion/contacts/always_on.ionrc). The script prepends one reference
# time ("@ <UTC>") so all three nodes load an identical plan. Set ION_T0
# (format yyyy/mm/dd-hh:mm:ss, UTC) to choose that reference time; the
# default is the current time. The value used is written to
# $ION_RUN_DIR/t0.
#
# Each node gets a fresh working directory $ION_RUN_DIR/<node> (default
# build/run/ion/<node>) holding its config files, ion.log and SDR log.
# The link emulator (or ion/udp_forward.py) must be started separately; the
# nodes start without it, and LTP retransmits until it is up.
#
# Refuses to start if ION processes, the demo's shared-memory keys or ION
# POSIX semaphores already exist (run ion/stop_nodes.sh first).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=env.sh
source "$HERE/env.sh"
# shellcheck source=lib.sh
source "$HERE/lib.sh"

PLAN="${1:-$HERE/contacts/always_on.ionrc}"
[[ -f "$PLAN" ]] || { echo "start_nodes: no contact plan $PLAN" >&2; exit 1; }
[[ -x "$ION_PREFIX/bin/ionadmin" ]] || { echo "start_nodes: ION not built; run ion/build_ion.sh" >&2; exit 1; }

if ! ion_state_clean; then
  echo "start_nodes: ION state already present on this host:" >&2
  ion_state_report | sed 's/^/  /' >&2
  echo "start_nodes: run ion/stop_nodes.sh first" >&2
  exit 1
fi

T0="${ION_T0:-$(date -u +%Y/%m/%d-%H:%M:%S)}"
rm -rf "$ION_RUN_DIR"
mkdir -p "$ION_RUN_DIR"
echo "$T0" >"$ION_RUN_DIR/t0"

# Start order: gateway first, then rover and earth. All nodes use the same
# sdrWmSize, so order does not matter to ION; gateway first means both
# neighbours find their peer engine already running.
for name in gateway rover earth; do
  dir="$ION_RUN_DIR/$name"
  mkdir -p "$dir"
  for f in "$HERE/nodes/$name"/*; do
    sed "s|@NODE_DIR@|$dir|g" "$f" >"$dir/$(basename "$f")"
  done
  { echo "# Generated by ion/start_nodes.sh from $(basename "$PLAN")"
    echo "@ $T0"
    cat "$PLAN"; } >"$dir/contacts.ionrc"

  # Daemons spawned by the admin programs inherit stdout/stderr, so these
  # must go to a file (a pipe would never reach end-of-file).
  if ! ( cd "$dir" && export ION_NODE_WDNAME="$dir" &&
         ionadmin node.ionrc && ionadmin contacts.ionrc &&
         ionsecadmin node.ionsecrc && ltpadmin node.ltprc && bpadmin node.bprc
       ) >"$dir/start.log" 2>&1 </dev/null; then
    echo "start_nodes: $name failed to start; see $dir/start.log and $dir/ion.log" >&2
    exit 1
  fi
  if ! ion_wait_ready "$dir" 30; then
    echo "start_nodes: $name did not report ready within 30 s; see $dir/ion.log" >&2
    exit 1
  fi
  echo "start_nodes: $name (ipn:$(ion_node_nbr "$name")) running in $dir"
done
echo "start_nodes: contact plan $(basename "$PLAN"), reference time $T0 UTC"
